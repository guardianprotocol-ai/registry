#!/usr/bin/env python3
"""Write each pattern's false alarm rate from the benign corpus, and publish the table.

    python3 scripts/build_false_alarms.py            write the rates and the page
    python3 scripts/build_false_alarms.py --check    fail if either is out of date

Every pattern file shipped with `false_alarm_rate: null` and the comment in
`docs/pattern-template.yaml` says it is "filled in by the checks once the benign corpus
exists". The corpus has existed for weeks. Until this script, the registry published an
attack success rate with an interval and a denominator for every pattern and no false
alarm rate for any of them, which is the first thing anybody asks a detection tool.

The rate is the share of benign corpus cases that a pattern's rule flags. A rate alone
would be the same mistake the attack matrix exists to avoid, so the page carries the
denominator and a 95% Wilson interval: none of 24 supports "under 14%", which is a
statement, where a bare 0.0 reads as a promise.

**A pattern with no rule gets no rate, not a zero.** Six patterns are documented ideas
with nothing implemented, and the gate reports them as flagging nothing because there is
nothing to flag. Writing 0.0 there would say a rule never false alarms about a rule that
does not exist. Those stay null and the page says why.

Python 3.9+ standard library only.
"""
import argparse
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "sensor"))
sys.path.insert(0, os.path.join(ROOT, "scanner"))
from guardian_sensor import rules  # noqa: E402
from guardian_scanner.results import wilson  # noqa: E402

PAGE = os.path.join(ROOT, "docs", "FALSE_ALARMS.md")
RATE_LINE = re.compile(r"^(\s*false_alarm_rate:\s*)(.+?)(\s*(?:#.*)?)$", re.M)


def gate():
    """What the rule gate saw, as a document. Run rather than imported, so this reads the
    same numbers CI enforces rather than a second implementation of them."""
    out = subprocess.run([sys.executable, os.path.join(ROOT, "scripts", "rule_gate.py"),
                          "--json"], capture_output=True, text=True, cwd=ROOT)
    return json.loads(out.stdout)


def rated():
    """Patterns the rate means something for: the ones with a rule behind them."""
    return set(rules.RULES)


def rate_for(pattern, report):
    per = report.get("per_pattern", {}).get(pattern) or {}
    return per.get("false_alarm_rate")


def pattern_files():
    folder = os.path.join(ROOT, "patterns")
    return [(name[:-5], os.path.join(folder, name))
            for name in sorted(os.listdir(folder)) if name.endswith(".yaml")]


def wanted(pattern, report):
    """The value this pattern's file should carry, as text."""
    if pattern not in rated():
        return "null"
    value = rate_for(pattern, report)
    return "null" if value is None else repr(round(float(value), 4))


def write_files(report, check=False):
    stale = []
    for pattern, path in pattern_files():
        with open(path, encoding="utf-8") as f:
            text = f.read()
        match = RATE_LINE.search(text)
        if not match:
            stale.append("%s has no false_alarm_rate line" % pattern)
            continue
        value = wanted(pattern, report)
        if match.group(2).strip() == value:
            continue
        if check:
            stale.append("%s says %s, the corpus says %s"
                         % (pattern, match.group(2).strip(), value))
            continue
        with open(path, "w", encoding="utf-8") as f:
            f.write(text[:match.start()] + match.group(1) + value + match.group(3)
                    + text[match.end():])
    return stale


def page_text(report):
    benign = report.get("benign", [])
    total = len(benign)
    known = {b["id"]: b.get("known_false_alarm") for b in benign if b.get("known_false_alarm")}
    lines = [
        "# False alarms",
        "",
        "Generated by `python3 scripts/build_false_alarms.py` from the benign corpus. Do not",
        "edit by hand: `python3 check.py` fails if this file and the corpus disagree.",
        "",
        "A detection rate means nothing on its own. A rule that catches every attack and also",
        "stops ordinary work is an outage, and the only honest way to say a rule is useful is",
        "to publish both numbers with the same care.",
        "",
        "**The denominator is %d cases of ordinary agent work** that no rule may flag. It is"
        % total,
        "shared by every rule rather than owned by one pattern, so the same cases are counted",
        "for each row. That makes this a floor, not a field measurement: these are the false",
        "alarms we wrote cases for, never the ones a real deployment would find.",
        "",
        "**None of %d supports \"under %.0f%%\", not \"never\".** The interval is what makes that"
        % (total, wilson(0, total)[1] * 100),
        "difference readable, which is the same reason every cell in the attack matrix carries",
        "one.",
        "",
        "**A pattern with no rule has no rate.** Six patterns are documented ideas with nothing",
        "implemented. The gate reports them flagging nothing because there is nothing to flag,",
        "and writing a zero there would claim a rule never false alarms about a rule that does",
        "not exist.",
        "",
        "| Pattern | Flagged | Of | Rate | 95% interval |",
        "| --- | --- | --- | --- | --- |",
    ]
    for pattern, _ in pattern_files():
        if pattern not in rated():
            lines.append("| %s | no rule yet | | | |" % pattern)
            continue
        flagged = report.get("per_pattern", {}).get(pattern, {}).get("benign_flagged", [])
        low, high = wilson(len(flagged), total)
        lines.append("| %s | %d | %d | %.1f%% | [%.2f, %.2f] |"
                     % (pattern, len(flagged), total, 100.0 * len(flagged) / total, low, high))
    lines += ["", "## Known false alarms", ""]
    if known:
        lines.append("Marked in the case itself, never hidden. A reported false alarm becomes a")
        lines.append("benign case, and one that is understood and not yet fixed says so.")
        lines.append("")
        lines.append("| Case | Pattern |")
        lines.append("| --- | --- |")
        for case, pattern in sorted(known.items()):
            lines.append("| `%s` | %s |" % (case, pattern))
    else:
        lines.append("None recorded.")
    lines.append("")
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if anything is out of date")
    a = ap.parse_args(argv)
    report = gate()

    stale = write_files(report, check=a.check)
    text = page_text(report)
    current = ""
    if os.path.exists(PAGE):
        with open(PAGE, encoding="utf-8") as f:
            current = f.read()
    if a.check:
        if current != text:
            stale.append("docs/FALSE_ALARMS.md is out of date")
        if stale:
            for line in stale:
                print(line)
            print("Regenerate it:\n  python3 scripts/build_false_alarms.py")
            return 1
        print("False alarm rates are current.")
        return 0
    with open(PAGE, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote %s and the rate in every pattern file" % PAGE)
    return 0


if __name__ == "__main__":
    sys.exit(main())
